"""Kiểm tra tái lập cho notebook thống kê FD001.

Chạy pytest, chạy notebook 02 hai lần từ kernel mới rồi so sánh artifact.
Notebook chạy dưới một runtime guard chặn mở `test_FD001.txt` và `RUL_FD001.txt`.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time
from typing import Any, Iterable, Sequence

from .artifact_io import sha256_file, write_json

BLOCKED_TEST_FILENAMES = ("test_FD001.txt", "RUL_FD001.txt")
TRAIN_FILENAME = "train_FD001.txt"
TRAIN_ONLY_AUDIT_RULE = "STATISTICS_TRAIN_ONLY"
TRAIN_ONLY_AUTHORITY = (
    "docs/plans/active/2026-09-21-cmapss-rul-final-report.md"
    "#m24-validation-va-tai-lap"
)
STABLE_OUTPUTS = (
    "outputs/statistics/tables/engine_sensor_pairs.csv",
    "outputs/statistics/tables/sensor_inference.csv",
    "outputs/statistics/figures/difference_distributions.png",
    "outputs/statistics/figures/effect_size_ci.png",
)
RAW_FILES = (
    "data/raw/train_FD001.txt",
    "data/raw/test_FD001.txt",
    "data/raw/RUL_FD001.txt",
)


class ValidationCommandError(RuntimeError):
    """Command validation thất bại hoặc kết quả không tái lập."""


def _guard_source() -> str:
    blocked = ", ".join(repr(name) for name in BLOCKED_TEST_FILENAMES)
    return f'''"""Runtime guard generated by cmapss.statistics.reproducibility."""
import builtins
from pathlib import Path

_BLOCKED_TEST_FILENAMES = {{{blocked}}}
_RULE = {TRAIN_ONLY_AUDIT_RULE!r}
_AUTHORITY = {TRAIN_ONLY_AUTHORITY!r}
_ORIGINAL_OPEN = builtins.open
_ORIGINAL_PATH_OPEN = Path.open


def _check_train_only_path(file):
    try:
        path = Path(file)
    except TypeError:
        return
    if path.name in _BLOCKED_TEST_FILENAMES:
        display = path.as_posix()
        raise PermissionError(
            f"[{{_RULE}}] {{display}}: thống kê suy luận chỉ được đọc "
            f"data/raw/{TRAIN_FILENAME}; chặn test observations/test labels "
            f"theo {{_AUTHORITY}}. Hành động: dùng {TRAIN_FILENAME} cho "
            "paired sensor inference và chỉ dùng test_FD001.txt/RUL_FD001.txt "
            "ở bước final evaluation."
        )


def _guarded_open(file, *args, **kwargs):
    _check_train_only_path(file)
    return _ORIGINAL_OPEN(file, *args, **kwargs)


def _guarded_path_open(self, *args, **kwargs):
    _check_train_only_path(self)
    return _ORIGINAL_PATH_OPEN(self, *args, **kwargs)


builtins.open = _guarded_open
Path.open = _guarded_path_open
'''


def write_train_only_audit_guard(guard_dir: Path) -> Path:
    """Ghi `sitecustomize.py` vào `guard_dir` để chặn đọc hai file test.

    Guard chỉ có hiệu lực khi `guard_dir` nằm trong `PYTHONPATH`.
    """
    guard_dir.mkdir(parents=True, exist_ok=True)
    guard_path = guard_dir / "sitecustomize.py"
    guard_path.write_text(_guard_source(), encoding="utf-8")
    return guard_path


def guarded_python_env(guard_dir: Path, base_env: dict[str, str] | None = None) -> dict[str, str]:
    """Environment có `guard_dir` đứng đầu `PYTHONPATH` để Python tự nạp guard."""
    env = dict(base_env or os.environ)
    current_pythonpath = env.get("PYTHONPATH")
    guard_path = str(guard_dir)
    env["PYTHONPATH"] = guard_path if not current_pythonpath else guard_path + os.pathsep + current_pythonpath
    env["PYTHONIOENCODING"] = "utf-8"
    env.setdefault("MPLBACKEND", "module://matplotlib_inline.backend_inline")
    return env


def _stringify_command(command: Sequence[str]) -> str:
    return " ".join(command)


def _run_command(
    command: Sequence[str],
    *,
    cwd: Path,
    env: dict[str, str] | None = None,
    expect_success: bool = True,
) -> subprocess.CompletedProcess[str]:
    completed = subprocess.run(
        list(command),
        cwd=cwd,
        env=env,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if expect_success and completed.returncode != 0:
        raise ValidationCommandError(
            f"Command failed with exit code {completed.returncode}: {_stringify_command(command)}\n"
            f"STDOUT:\n{completed.stdout}\nSTDERR:\n{completed.stderr}"
        )
    return completed


def _parse_pytest_result(output: str) -> dict[str, int]:
    match = re.search(r"(?P<passed>\d+) passed(?:, (?P<skipped>\d+) skipped)?", output)
    if not match:
        raise ValidationCommandError(f"Không đọc được số test passed từ pytest output:\n{output}")
    return {
        "passed": int(match.group("passed")),
        "skipped": int(match.group("skipped") or 0),
        "failed": 0,
    }


def _run_pytest(command: Sequence[str], *, cwd: Path) -> dict[str, Any]:
    start = time.perf_counter()
    completed = _run_command(command, cwd=cwd)
    elapsed = time.perf_counter() - start
    parsed = _parse_pytest_result(completed.stdout + completed.stderr)
    return {
        "command": _stringify_command(command),
        "exit_code": completed.returncode,
        "seconds": round(elapsed, 2),
        **parsed,
    }


def _raw_hashes(project_root: Path) -> dict[str, str]:
    return {relative_path: sha256_file(project_root / relative_path) for relative_path in RAW_FILES}


def _stable_output_hashes(project_root: Path) -> dict[str, str]:
    return {relative_path: sha256_file(project_root / relative_path) for relative_path in STABLE_OUTPUTS}


def _load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _stable_run_info(project_root: Path) -> dict[str, Any]:
    run_info = _load_json(project_root / "outputs/statistics/run_info.json")
    return {
        key: run_info[key]
        for key in (
            "input",
            "input_sha256",
            "versions",
            "test_data_used",
            "test_labels_used",
            "window_cycles",
            "difference_definition",
            "unit_of_analysis",
            "sensor_family",
            "config",
            "observations",
            "engines",
            "pair_rows",
            "inference_rows",
            "tables",
        )
    }


def _stable_validation_payload(project_root: Path) -> dict[str, Any]:
    validation = _load_json(project_root / "outputs/statistics/validation.json")
    return {
        key: validation[key]
        for key in (
            "status",
            "test_data_used",
            "test_labels_used",
            "raw_sha256_unchanged",
            "config_matches_m20",
            "engine_sensor_pairs",
            "sensor_inference",
        )
    }


def _run_guard_probe(*, project_root: Path, python_executable: Path, env: dict[str, str]) -> dict[str, Any]:
    positive_code = (
        "from pathlib import Path; "
        f"Path('data/raw/{TRAIN_FILENAME}').open('rb').read(1); "
        "print('train read allowed')"
    )
    positive = _run_command([str(python_executable), "-c", positive_code], cwd=project_root, env=env)

    negative_proof = []
    for filename in BLOCKED_TEST_FILENAMES:
        code = (
            "from pathlib import Path; "
            f"Path('data/raw/{filename}').open('rb').read(1)"
        )
        blocked = _run_command(
            [str(python_executable), "-c", code],
            cwd=project_root,
            env=env,
            expect_success=False,
        )
        combined_output = blocked.stdout + blocked.stderr
        if blocked.returncode == 0 or TRAIN_ONLY_AUDIT_RULE not in combined_output or filename not in combined_output:
            raise ValidationCommandError(
                f"Runtime guard không chặn đúng {filename}.\nSTDOUT:\n{blocked.stdout}\nSTDERR:\n{blocked.stderr}"
            )
        negative_proof.append(
            {
                "file": filename,
                "exit_code": blocked.returncode,
                "diagnostic_contains": [TRAIN_ONLY_AUDIT_RULE, filename, TRAIN_ONLY_AUTHORITY],
            }
        )

    return {
        "status": "passed",
        "rule": TRAIN_ONLY_AUDIT_RULE,
        "authority": TRAIN_ONLY_AUTHORITY,
        "positive_train_read": positive.stdout.strip(),
        "blocked_files": list(BLOCKED_TEST_FILENAMES),
        "negative_proof": negative_proof,
    }


def _run_notebook(
    *,
    project_root: Path,
    python_executable: Path,
    notebook_path: Path,
    env: dict[str, str],
    timeout_seconds: int,
) -> dict[str, Any]:
    command = [
        str(python_executable),
        "-m",
        "nbconvert",
        "--to",
        "notebook",
        "--execute",
        "--inplace",
        str(notebook_path),
        f"--ExecutePreprocessor.timeout={timeout_seconds}",
        "--ExecutePreprocessor.kernel_name=python3",
    ]
    start = time.perf_counter()
    notebook_env = {
        **env,
        "CMAPSS_STATISTICS_NOTEBOOK_OUTPUT": str(project_root / "outputs/statistics"),
    }
    completed = _run_command(command, cwd=project_root, env=notebook_env)
    elapsed = time.perf_counter() - start
    return {
        "command": _stringify_command(command),
        "exit_code": completed.returncode,
        "seconds": round(elapsed, 2),
        "fresh_kernel": True,
    }


def _copy_stable_outputs(project_root: Path, destination: Path) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    for relative_path in STABLE_OUTPUTS:
        target = destination / relative_path
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(project_root / relative_path, target)
    for relative_path in ("outputs/statistics/run_info.json", "outputs/statistics/validation.json"):
        target = destination / relative_path
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(project_root / relative_path, target)


def _compare_repeated_runs(first: dict[str, Any], second: dict[str, Any]) -> dict[str, Any]:
    comparisons = {
        "stable_output_hashes_identical": first["stable_output_hashes"] == second["stable_output_hashes"],
        "run_info_result_fields_identical": first["run_info"] == second["run_info"],
        "validation_result_fields_identical": first["validation"] == second["validation"],
    }
    if not all(comparisons.values()):
        raise ValidationCommandError(f"Repeated notebook runs are not reproducible: {comparisons}")
    csv_count = sum(path.endswith(".csv") for path in STABLE_OUTPUTS)
    png_count = sum(path.endswith(".png") for path in STABLE_OUTPUTS)
    return {
        "status": "passed",
        "fresh_kernel_runs": 2,
        "identical_csv_files": csv_count,
        "identical_png_files": png_count,
        "comparisons": comparisons,
        "stable_output_sha256": second["stable_output_hashes"],
    }


def validate_statistics_reproducibility(
    *,
    project_root: Path,
    notebook: Path,
    output_dir: Path,
    work_dir: Path,
    timeout_seconds: int,
    python_executable: Path = Path(sys.executable),
) -> dict[str, Any]:
    """Chạy toàn bộ kiểm tra tái lập và ghi kết quả vào `validation.json`."""
    project_root = project_root.resolve()
    notebook = notebook if notebook.is_absolute() else project_root / notebook
    output_dir = output_dir if output_dir.is_absolute() else project_root / output_dir
    work_dir = work_dir if work_dir.is_absolute() else project_root / work_dir

    guard_dir = work_dir / "runtime-guard"
    snapshot_dir = work_dir / "snapshots"
    write_train_only_audit_guard(guard_dir)
    guarded_env = guarded_python_env(guard_dir)

    raw_before = _raw_hashes(project_root)

    focused_pytest = _run_pytest(
        [
            str(python_executable),
            "-m",
            "pytest",
            "tests/test_statistics_pairs.py",
            "tests/test_statistics_inference.py",
            "tests/test_statistics_artifacts.py",
            "tests/test_statistics_reproducibility.py",
            "-q",
            "--basetemp=tmp/pytest-statistics-m24",
            "--tb=short",
        ],
        cwd=project_root,
    )
    full_pytest = _run_pytest(
        [
            str(python_executable),
            "-m",
            "pytest",
            "-q",
            "--basetemp=tmp/pytest-m24-full",
            "--tb=short",
        ],
        cwd=project_root,
    )
    guard_probe = _run_guard_probe(project_root=project_root, python_executable=python_executable, env=guarded_env)

    notebook_runs = []
    repeated_snapshots = []
    for run_index in (1, 2):
        notebook_runs.append(
            _run_notebook(
                project_root=project_root,
                python_executable=python_executable,
                notebook_path=notebook,
                env=guarded_env,
                timeout_seconds=timeout_seconds,
            )
        )
        run_snapshot = {
            "stable_output_hashes": _stable_output_hashes(project_root),
            "run_info": _stable_run_info(project_root),
            "validation": _stable_validation_payload(project_root),
        }
        repeated_snapshots.append(run_snapshot)
        _copy_stable_outputs(project_root, snapshot_dir / f"run-{run_index}")

    reproducibility = _compare_repeated_runs(repeated_snapshots[0], repeated_snapshots[1])
    raw_after = _raw_hashes(project_root)
    raw_unchanged = raw_before == raw_after
    if not raw_unchanged:
        raise ValidationCommandError("Raw SHA-256 changed during validation.")

    validation_path = output_dir / "validation.json"
    validation = _load_json(validation_path)
    validation["scope"] = (
        "M2.3a artifact validation plus M2.4 local repeated-run and "
        "train-only runtime audit for sensor inference"
    )
    validation["raw_sha256_unchanged"] = validation.get("raw_sha256_unchanged") and raw_unchanged
    validation["test_reads_blocked_by_runtime_audit"] = True
    validation["audit_negative_proof"] = list(BLOCKED_TEST_FILENAMES)
    validation["notebook_repeated_runs"] = 2
    validation["identical_csv_files"] = reproducibility["identical_csv_files"]
    validation["identical_png_files"] = reproducibility["identical_png_files"]
    validation["m2_4_validation"] = {
        "status": "passed",
        "authority": TRAIN_ONLY_AUTHORITY,
        "local_validation_owner": "pytest plus python -m nbconvert",
        "focused_pytest": focused_pytest,
        "full_pytest": full_pytest,
        "runtime_audit": guard_probe,
        "notebook_runs": notebook_runs,
        "reproducibility": reproducibility,
        "raw_sha256_before": raw_before,
        "raw_sha256_after": raw_after,
        "raw_sha256_unchanged": raw_unchanged,
        "snapshot_dir": snapshot_dir.relative_to(project_root).as_posix(),
        "enforcement": {
            "local_validation": "passed",
            "optional_hook": "not found",
            "ci_invocation": "not found in this repository",
            "branch_protection": "unverified external setting",
        },
    }
    checks = list(validation.get("checks", []))
    checks.extend(
        [
            "focused statistics pytest passed",
            "full pytest suite passed",
            "notebook executed twice from fresh kernels under train-only runtime guard",
            "stable CSV and PNG outputs were identical across repeated notebook runs",
            "runtime guard blocked test_FD001.txt and RUL_FD001.txt in negative probes",
            "raw train/test/label SHA-256 unchanged before and after validation",
        ]
    )
    validation["checks"] = checks
    write_json(validation_path, validation)
    return validation


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Run statistics reproducibility validation.")
    parser.add_argument("--project-root", type=Path, default=Path("."))
    parser.add_argument("--notebook", type=Path, default=Path("notebooks/02_fd001_inference.ipynb"))
    parser.add_argument("--output-dir", type=Path, default=Path("outputs/statistics"))
    parser.add_argument("--work-dir", type=Path, default=Path("tmp/statistics-reproducibility-m24"))
    parser.add_argument("--timeout", type=int, default=1800)
    return parser


def main(argv: Iterable[str] | None = None) -> int:
    """Entry point cho `python -m cmapss.statistics.reproducibility`."""
    args = _build_parser().parse_args(list(argv) if argv is not None else None)
    validation = validate_statistics_reproducibility(
        project_root=args.project_root,
        notebook=args.notebook,
        output_dir=args.output_dir,
        work_dir=args.work_dir,
        timeout_seconds=args.timeout,
    )
    print(json.dumps(validation["m2_4_validation"], ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
